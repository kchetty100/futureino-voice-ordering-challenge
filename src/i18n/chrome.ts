export type ChromeKey = keyof typeof ROWS;

/** Labels painted on the kiosk. Product names stay English. */
export function ui(language: AppLanguage | null | undefined, key: ChromeKey, params: Record<string, string | number | undefined> = {}): string {
  const lang: AppLanguage = language && ROWS[key][language] ? language : "en";
  let out: string = ROWS[key][lang];
  for (const [name, value] of Object.entries(params)) {
    out = out.replaceAll(`{${name}}`, value == null ? "" : String(value));
  }
  return out;
}
